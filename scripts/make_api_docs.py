"""Write docs/openapi.json and docs/api.md from the live FastAPI app definition."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from cliniq.api.app import app  # noqa: E402

from cliniq.api.app import current_user  # noqa: E402


def min_role(route) -> str:
    """Read the role straight from the route's require(role) dependency, so docs cannot drift."""
    for d in route.dependant.dependencies:
        if getattr(d.call, "__name__", "") == "dep" and d.call.__closure__:
            return d.call.__closure__[0].cell_contents
        if d.call is current_user:
            return "any"
    return "public"


ROLES = {(m, r.path): min_role(r) for r in app.routes if hasattr(r, "dependant") for m in getattr(r, "methods", [])}
spec = app.openapi()
(ROOT / "docs" / "openapi.json").write_text(json.dumps(spec, indent=1))
out = ["# CLINIQ API reference", "",
       "Generated by `scripts/make_api_docs.py` from the FastAPI app. Interactive docs: `http://localhost:8000/docs`.", "",
       "Authentication: `Authorization: Bearer <token>`. Roles: viewer < researcher < admin. Long-running operations "
       "(ingest, dbt, reindex, DLQ retry, benchmarks) return **202** with a `job_id`; poll `GET /api/jobs/{job_id}`. "
       "Pass `?wait=true` to run them synchronously. Every response carries an `X-Request-ID` header.", ""]
for tag in [t["name"] for t in spec.get("tags", [])]:
    out += [f"## {tag}", "", "| Method | Path | Min. role | Summary |", "|---|---|---|---|"]
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            if tag in op.get("tags", []):
                role = ROLES.get((method.upper(), path), "?")
                out.append(f"| {method.upper()} | `{path}` | {role} | {op.get('summary', '')} |")
    out.append("")
(ROOT / "docs" / "api.md").write_text("\n".join(out))
print("wrote docs/api.md and docs/openapi.json")
